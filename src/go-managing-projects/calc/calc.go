package calc

func plus (a int, b int) int {
	return a + b
}

func Minus (a int, b int) int {
	return a - b
}

func Multi (a int, b int) int {
	return a * b
}

func Divide (a int, b int) int {
	return a / b
}

func Discount (a, b int) float32 {
	return float32(a * b) / 100
}


